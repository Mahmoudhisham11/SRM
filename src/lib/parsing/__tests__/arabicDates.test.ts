import { describe, expect, it } from "vitest";
import { parseSpokenDate } from "../arabicDates";

// Fixed "today" so relative dates are deterministic.
const ctx = { defaultYear: 2025, today: "2026-11-11" };
const p = (text: string, c = ctx) => parseSpokenDate(text, c);

describe("parseSpokenDate — month names", () => {
  const cases: Array<[string, string]> = [
    ["15 مارس", "2025-03-15"],
    ["١٥ مارس", "2025-03-15"],
    ["15 مارس 2024", "2024-03-15"],
    ["١٥ مارس ٢٠٢٤", "2024-03-15"],
    ["15 من مارس", "2025-03-15"],
    ["1 يناير", "2025-01-01"],
    ["28 فبراير", "2025-02-28"],
    ["10 ابريل", "2025-04-10"],
    ["10 أبريل", "2025-04-10"],
    ["10 إبريل", "2025-04-10"],
    ["5 مايو", "2025-05-05"],
    ["20 يونيو", "2025-06-20"],
    ["20 يونيه", "2025-06-20"],
    ["4 يوليو", "2025-07-04"],
    ["31 أغسطس", "2025-08-31"],
    ["31 اغسطس", "2025-08-31"],
    ["9 سبتمبر", "2025-09-09"],
    ["6 أكتوبر", "2025-10-06"],
    ["6 اكتوبر", "2025-10-06"],
    ["25 نوفمبر", "2025-11-25"],
    ["25 ديسمبر", "2025-12-25"],
    ["مارس 15", "2025-03-15"],
    ["March 15", "2025-03-15"],
    ["15 march 2024", "2024-03-15"],
    ["15 Mar", "2025-03-15"],
    ["dec 1 2023", "2023-12-01"],
    ["15 آذار", "2025-03-15"],
    ["10 تشرين الأول", "2025-10-10"],
    ["15 مارس سنة 2024", "2024-03-15"],
    ["15 مارس سنة 24", "2024-03-15"],
    ["خمستاشر مارس", "2025-03-15"],
    ["واحد وعشرين ديسمبر", "2025-12-21"],
    ["تلاتين يونيو", "2025-06-30"],
    ["15 شهر مارس", "2025-03-15"],
  ];
  for (const [text, iso] of cases) it(`"${text}" → ${iso}`, () => expect(p(text)).toBe(iso));
});

describe("parseSpokenDate — numeric forms", () => {
  const cases: Array<[string, string]> = [
    ["15/3", "2025-03-15"],
    ["١٥/٣", "2025-03-15"],
    ["15-3", "2025-03-15"],
    ["15.3", "2025-03-15"],
    ["15/3/2024", "2024-03-15"],
    ["15/03/2024", "2024-03-15"],
    ["15/3/24", "2024-03-15"],
    ["١٥/٣/٢٠٢٤", "2024-03-15"],
    ["2024-03-15", "2024-03-15"],
    ["15 / 3", "2025-03-15"],
    ["15 - 3 - 2024", "2024-03-15"],
    ["15 3", "2025-03-15"],
    ["15 3 2024", "2024-03-15"],
    ["15/3 2024", "2024-03-15"],
    ["15 شهر 3", "2025-03-15"],
    ["1/12", "2025-12-01"],
  ];
  for (const [text, iso] of cases) it(`"${text}" → ${iso}`, () => expect(p(text)).toBe(iso));
});

describe("parseSpokenDate — spoken Egyptian numbers", () => {
  const cases: Array<[string, string]> = [
    ["خمستاشر تلاتة", "2025-03-15"],
    ["خمستاشر تلاته", "2025-03-15"],
    ["واحد وعشرين اتناشر", "2025-12-21"],
    ["تلاتة عشرة", "2025-10-03"], // Egyptian: day 3, month 10
    ["خمسة عشر شهر تلاتة", "2025-03-15"], // MSA teen
    ["اتنين شهر تمانية", "2025-08-02"],
    ["عشرة تلاتة", "2025-03-10"],
    ["حداشر حداشر", "2025-11-11"],
    ["خمستاشر تلاتة الفين اربعة وعشرين", "2024-03-15"],
    ["خمستاشر تلاتة ألفين وأربعة وعشرين", "2024-03-15"],
    ["خمستاشر تلاتة سنة اربعة وعشرين", "2024-03-15"],
    ["تمنتاشر سبعة", "2025-07-18"],
  ];
  for (const [text, iso] of cases) it(`"${text}" → ${iso}`, () => expect(p(text)).toBe(iso));
});

describe("parseSpokenDate — relative words (use real today, not default year)", () => {
  const cases: Array<[string, string]> = [
    ["النهارده", "2026-11-11"],
    ["النهاردة", "2026-11-11"],
    ["اليوم", "2026-11-11"],
    ["today", "2026-11-11"],
    ["امبارح", "2026-11-10"],
    ["إمبارح", "2026-11-10"],
    ["أمس", "2026-11-10"],
    ["yesterday", "2026-11-10"],
    ["اول امبارح", "2026-11-09"],
    ["أول إمبارح", "2026-11-09"],
    ["بكرة", "2026-11-12"],
    ["بعد بكرة", "2026-11-13"],
  ];
  for (const [text, iso] of cases) it(`"${text}" → ${iso}`, () => expect(p(text)).toBe(iso));

  it("crosses month/year boundaries", () => {
    expect(p("امبارح", { defaultYear: 2025, today: "2026-01-01" })).toBe("2025-12-31");
    expect(p("اول امبارح", { defaultYear: 2025, today: "2024-03-01" })).toBe("2024-02-28");
  });
});

describe("parseSpokenDate — first/last of month", () => {
  it("اول مارس", () => expect(p("اول مارس")).toBe("2025-03-01"));
  it("آخر فبراير (non-leap)", () => expect(p("آخر فبراير")).toBe("2025-02-28"));
  it("آخر فبراير 2024 (leap)", () => expect(p("آخر فبراير 2024")).toBe("2024-02-29"));
  it("اخر شهر 4", () => expect(p("اخر شهر 4")).toBe("2025-04-30"));
});

describe("parseSpokenDate — filler words and surrounding speech", () => {
  const cases: Array<[string, string]> = [
    ["يوم 15 مارس", "2025-03-15"],
    ["بتاريخ 15/3", "2025-03-15"],
    ["في 15 مارس", "2025-03-15"],
    ["كان يوم خمستاشر تلاتة تقريبا", "2025-03-15"],
    ["التاريخ 2 فبراير", "2025-02-02"],
  ];
  for (const [text, iso] of cases) it(`"${text}" → ${iso}`, () => expect(p(text)).toBe(iso));
});

describe("parseSpokenDate — default year", () => {
  it("uses the session default year when none is spoken", () => {
    expect(p("15 مارس", { defaultYear: 2024, today: "2026-11-11" })).toBe("2024-03-15");
    expect(p("29 فبراير", { defaultYear: 2024, today: "2026-11-11" })).toBe("2024-02-29");
  });
});

describe("parseSpokenDate — invalid input", () => {
  const bad = ["", "مارس", "كلام عادي", "32 مارس", "30 فبراير", "15 13", "15/13", "0/3", "29 فبراير", "ألف مارس"];
  for (const text of bad) it(`"${text}" → null`, () => expect(p(text)).toBeNull());
});
